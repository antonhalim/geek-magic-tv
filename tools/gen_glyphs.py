"""Render the Chinese characters the faces need into 1-bit bitmaps.

Usage:
  python gen_glyphs.py <NotoSansSC.ttf> sc > ../src/faces/cjk_glyphs.h   (Chongqing, simplified)
  python gen_glyphs.py <NotoSansTC.ttf> tc > ../src/faces/hk_glyphs.h    (Hong Kong, traditional)
Needs Pillow. Use Noto Sans SC / TC (SIL Open Font License); a Google Fonts subset
with just these characters is enough:
https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@500&text=<chars>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SETS = {
    "sc": {
        "font": "Noto Sans SC", "enum": "CjkGlyph", "prefix": "CJK", "sizes": [16],
        "glyphs": [  # (enum name, character)
            ("ZHONG", "重"), ("QING", "庆"), ("YU", "渝"), ("HUO", "火"), ("GUO", "锅"),
            ("LI", "李"), ("ZI", "子"), ("BA", "坝"), ("ZHAN", "站"),
            ("SUNNY", "晴"), ("CLOUD", "云"), ("OVERCAST", "阴"), ("FOG", "雾"),
            ("RAIN", "雨"), ("SNOW", "雪"), ("THUNDER", "雷"),
        ],
    },
    "tc": {
        "font": "Noto Sans TC", "enum": "HkGlyph", "prefix": "HK", "sizes": [16, 12],
        "glyphs": [
            ("YA", "押"), ("CHA", "茶"), ("CAN", "餐"), ("TING", "廳"), ("MA", "麻"), ("QUE", "雀"),
            ("JIU", "酒"), ("JIA", "家"), ("XIANG", "香"), ("GANG", "港"), ("DING", "叮"),
            ("DIAN", "電"), ("CHE", "車"), ("TIAN", "天"), ("QI", "氣"),
            ("SUNNY", "晴"), ("CLOUD", "雲"), ("OVERCAST", "陰"), ("FOG", "霧"),
            ("RAIN", "雨"), ("SNOW", "雪"), ("THUNDER", "雷"),
        ],
    },
}
THRESHOLD = 110  # 12 px is too dense for complex characters; use it only for simple ones


def render(font_path, ch, size):
    font = ImageFont.truetype(font_path, size)
    img = Image.new("L", (size, size), 0)
    ImageDraw.Draw(img).text((size / 2, size / 2), ch, font=font, fill=255, anchor="mm")
    rows = []
    for y in range(size):
        bits = [1 if img.getpixel((x, y)) >= THRESHOLD else 0 for x in range(size)]
        bits += [0] * (-len(bits) % 8)
        rows += [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
    return rows


def main():
    font_path, cfg = sys.argv[1], SETS[sys.argv[2]]
    p, glyphs = cfg["prefix"], cfg["glyphs"]
    out = [f"// Generated by tools/gen_glyphs.py from {cfg['font']} (SIL Open Font License 1.1).",
           "// 1-bit, MSB first, for TFT_eSPI drawBitmap(). Do not edit by hand.",
           "#pragma once", "#include <Arduino.h>", "",
           f"enum {cfg['enum']} {{"]
    out += [f"  {p}_{name},  // {ch}" for name, ch in glyphs]
    out += [f"  {p}_COUNT", "};", ""]
    for size in cfg["sizes"]:
        nbytes = size * ((size + 7) // 8)
        out.append(f"static const uint8_t {p}{size}[{p}_COUNT][{nbytes}] PROGMEM = {{")
        for name, ch in glyphs:
            data = ", ".join(f"0x{b:02X}" for b in render(font_path, ch, size))
            out.append(f"  {{{data}}},  // {ch}")
        out += ["};", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
