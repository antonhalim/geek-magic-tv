"""Bake the Orbit face's Earth into flash: land, clouds and city lights per pixel, the
ground track, and the shading tables the face uses at run time.

Usage:
  python gen_orbit.py > ../src/faces/orbit_data.h
No dependencies. The noise matches the browser mockup, so the device shows the same planet.
"""
import math

# Geometry (screen pixels). Earth is a big circle below the window; the limb is its top edge.
CX, CY, R = 100, 640, 520
MX, MY = 120, 178                 # your city's marker on the surface
GL = (10, 56, 230, 208, 14)       # window glass: x0, y0, x1, y1, corner radius
FR = (4, 51, 236, 213, 19)        # window frame
KT = 0.0227                       # hours of local time per pixel sideways at the marker's depth
KZ = 0.08                         # how much faster time changes towards the horizon
SKY_N = 96                        # atmosphere table length, in quarter pixels above the limb
M32 = 0xFFFFFFFF


def imul(a, b):
    return ((a & M32) * (b & M32)) & M32


def hash2(x, y):  # same bits as the JavaScript mockup
    h = (imul(x, 374761393) + imul(y, 668265263)) & M32
    h = imul(h ^ (h >> 13), 1274126177)
    return (h ^ (h >> 16)) / 4294967296


def vn(x, y):
    xi, yi = math.floor(x), math.floor(y)
    xf, yf = x - xi, y - yi
    u, v = xf * xf * (3 - 2 * xf), yf * yf * (3 - 2 * yf)
    a, b, c, d = hash2(xi, yi), hash2(xi + 1, yi), hash2(xi, yi + 1), hash2(xi + 1, yi + 1)
    return a + (b - a) * u + (c - a) * v + (a - b - c + d) * u * v


def fbm(x, y):
    s, a, f = 0.0, 0.5, 1.0
    for _ in range(4):
        s += a * vn(x * f, y * f)
        f *= 2.03
        a *= 0.5
    return s / 0.9375


def in_rr(x, y, b):
    x0, y0, x1, y1, r = b
    if x < x0 or x > x1 or y < y0 or y > y1:
        return False
    qx = max(x0 + r - x, 0, x - (x1 - r))
    qy = max(y0 + r - y, 0, y - (y1 - r))
    return qx * qx + qy * qy <= r * r


def surface(x, y):
    """(xw, z) ground coordinates for a pixel, or None above the limb or outside the glass."""
    px, py = x + 0.5, y + 0.5
    if not in_rr(px, py, GL):
        return None
    dx, dy = px - CX, py - CY
    d = math.hypot(dx, dy)
    if d >= R:
        return None
    xa = CX + math.atan2(dx, -dy) * R
    z = 48 / (R - d + 5)
    return (xa - MX) * z / 96, z


def proj(xw, z):
    h = 48 / z - 5
    d = R - h
    ang = (MX + xw * 96 / z - CX) / R
    return CX + d * math.sin(ang), CY - d * math.cos(ang)


def main():
    x0, x1 = GL[0], GL[2]
    tex_w = x1 - x0
    rows = [y for y in range(GL[1], GL[3]) if any(surface(x, y) for x in range(x0, x1))]
    tex_y0, tex_y1 = rows[0], rows[-1] + 1
    tex_h = tex_y1 - tex_y0

    tex = []
    for y in range(tex_y0, tex_y1):
        for x in range(x0, x1):
            s = surface(x, y)
            if not s:
                tex.append(0)
                continue
            xw, z = s
            land = fbm(xw * 2.4 + 11.3, z * 2.4 + 3.1)
            cld = fbm(xw * 4.2 + 40.7, z * 6 + 7.9)
            pop = fbm(xw * 9 + 90.1, z * 9 + 1.7)
            spk = hash2(math.floor(xw * 70) + 5000, math.floor(z * 70))
            q = max(0, min(31, round((cld - 0.40) / 0.6 * 31)))
            b = q
            if land > 0.56:
                b |= 32
                if land > 0.62:
                    b |= 64
                lt = 0.9 - (pop - 0.52) * 1.2
                if pop > 0.52 and spk > lt + 0.028:
                    b |= 128
            tex.append(b)

    # ground track: dashes of 3 px on, 3 px off along the station's path
    zm = 48 / (R - math.hypot(MX - CX, MY - CY) + 5)
    pts, z = [], 0.42
    while z < 7:
        pts.append(proj((z - zm) * 0.9, z))
        z *= 1.04
    track = set()
    run = 0.0
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        seg = math.hypot(bx - ax, by - ay)
        n = max(1, int(seg / 0.25))
        for i in range(n):
            t = i / n
            if (run + seg * t) % 6 < 3:
                x, y = int(ax + (bx - ax) * t), int(ay + (by - ay) * t)
                if tex_y0 <= y < tex_y1 and surface(x, y):
                    track.add((x, y))
        run += seg
    bpr = (tex_w + 7) // 8
    mask = [0] * (tex_h * bpr)
    for x, y in track:
        i = (y - tex_y0) * bpr + (x - x0) // 8
        mask[i] |= 0x80 >> ((x - x0) % 8)

    def table(name, ctype, vals):
        out.append(f"static const {ctype} {name}[{len(vals)}] PROGMEM = {{")
        for i in range(0, len(vals), 20):
            out.append("  " + ", ".join(str(v) for v in vals[i:i + 20]) + ",")
        out.append("};")

    clamp = lambda v: max(0, min(255, round(v)))
    hs = range(128)  # depth below the limb, whole pixels
    es = [i / 4 for i in range(SKY_N)]  # height above the limb

    out = ["// Generated by tools/gen_orbit.py. Do not edit by hand.",
           "#pragma once", "#include <Arduino.h>", "",
           f"static const int ORB_CX = {CX}, ORB_CY = {CY}, ORB_R = {R}, ORB_MX = {MX}, ORB_MY = {MY};",
           f"static const int GL_X0 = {GL[0]}, GL_Y0 = {GL[1]}, GL_X1 = {GL[2]}, GL_Y1 = {GL[3]}, GL_R = {GL[4]};",
           f"static const int FR_X0 = {FR[0]}, FR_Y0 = {FR[1]}, FR_X1 = {FR[2]}, FR_Y1 = {FR[3]}, FR_R = {FR[4]};",
           f"static const float ORB_KT = {KT}f;",
           f"static const int TEX_X0 = {x0}, TEX_Y0 = {tex_y0}, TEX_W = {tex_w}, TEX_H = {tex_h}, TRACK_BPR = {bpr};",
           f"static const int SKY_N = {SKY_N};", "",
           "// Per surface pixel: bits 0-4 cloud density (0.40..1.00 of the noise), 5 land,",
           "// 6 high land (snow cover), 7 city lights.",
           ]
    table("ORBIT_TEX", "uint8_t", tex)
    out.append("// Ground track pixels, 1 bit each, same rows and columns as ORBIT_TEX.")
    table("ORBIT_TRACK", "uint8_t", mask)
    out.append("// By depth below the limb: sideways time scale (8.8), haze, night rim glow, twilight strength.")
    table("ORB_FZ", "uint16_t", [round(256 * (1 + KZ * 48 / (h + 5))) for h in hs])
    table("ORB_HAZE", "uint8_t", [clamp(255 * 0.9 * math.exp(-h / 15)) for h in hs])
    table("ORB_RIM", "uint8_t", [clamp(255 * math.exp(-h / 12)) for h in hs])
    table("ORB_TWH", "uint8_t", [clamp(255 * math.exp(-h / 40)) for h in hs])
    out.append("// Atmosphere by quarter pixels above the limb: day glow, night airglow, sunrise colours (RGB).")
    day, night, tw = [], [], []
    for e in es:
        g1, g2 = math.exp(-e / 2), math.exp(-e / 7)
        day += [clamp(70 * g1 + 18 * g2), clamp(175 * g1 + 60 * g2), clamp(255 * math.exp(-e / 2.4) + 165 * g2)]
        ag = math.exp(-((e - 4.5) ** 2) / 1.4)
        night += [clamp(12 * ag), clamp(120 * ag), clamp(50 * ag + 55 * g1)]
        tw += [clamp(255 * math.exp(-e / 1.6)), clamp(120 * math.exp(-e / 2)), clamp(40 * math.exp(-e / 2.5))]
    table("ORB_SKY_DAY", "uint8_t", day)
    table("ORB_SKY_NIGHT", "uint8_t", night)
    table("ORB_SKY_TW", "uint8_t", tw)
    print("\n".join(out))


if __name__ == "__main__":
    main()
